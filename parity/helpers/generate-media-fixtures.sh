#!/usr/bin/env bash
# Reproducible synthetic audio fixtures; no downloaded or user-owned media inputs.
set -euo pipefail

replace=false
if [[ ${1:-} == --replace && $# == 1 ]]; then
  replace=true
elif [[ $# != 0 ]]; then
  printf 'Usage: %s [--replace]\n' "$0" >&2
  exit 2
fi

command -v ffmpeg >/dev/null || { printf 'FFmpeg is required.\n' >&2; exit 1; }
project_root=$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/../.." && pwd)
corpus="$project_root/work/generated-corpus"
owner="$project_root/work/generated-corpus.owner"
signature='taglib synthetic corpus v1'
if [[ -L "$project_root/work" || -L "$corpus" || -L "$owner" ]]; then
  printf 'Refusing a symlinked work/corpus/ownership path.\n' >&2
  exit 1
fi
mkdir -p "$project_root/work"

# Fixed destination and exact names keep --replace away from arbitrary CORPUS paths.
names=(
  sine-vbr-30s.mp3 pink-cbr-7s.mp3 sine-layer2-7s.mp2 pink-16bit-30s.flac
  sine-vorbis-7s.ogg pink-opus-30s.opus sine-speex-7s.spx sine-oggflac-7s.oga
  pink-aac-30s.m4a sine-alac-24bit-7s.m4a pink-pcm24-30s.wav sine-rf64-7s.wav
  sine-pcm16-7s.aiff sine-wavpack-7s.wv sine-trueaudio-7s.tta pink-wmav2-7s.wma
  sine-matroska-flac-7s.mka
)
if [[ -e "$corpus" && ! -d "$corpus" ]]; then
  printf 'Corpus destination is not a directory.\n' >&2
  exit 1
fi
shopt -s nullglob dotglob
existing=("$corpus"/*)
if ((${#existing[@]})); then
  if [[ "$replace" != true || ! -f "$owner" || $(<"$owner") != "$signature" ]]; then
    printf 'Existing corpus retained. Use --replace only for a corpus owned by this script.\n' >&2
    exit 1
  fi
  for entry in "${existing[@]}"; do
    known=false
    for name in "${names[@]}"; do
      if [[ "$entry" == "$corpus/$name" ]]; then known=true; break; fi
    done
    if [[ "$known" != true || ! -f "$entry" || -L "$entry" ]]; then
      printf 'Refusing to replace an unrecognized entry: %s\n' "$entry" >&2
      exit 1
    fi
  done
fi

encoder_list=$(ffmpeg -hide_banner -encoders 2>/dev/null)
for encoder in libmp3lame mp2 flac libvorbis libopus aac alac pcm_s24le pcm_s16le pcm_s16be wavpack tta wmav2; do
  if [[ "$encoder_list" != *" $encoder "* ]]; then
    printf 'Required FFmpeg encoder is unavailable: %s\n' "$encoder" >&2
    exit 1
  fi
done

staging=$(mktemp -d "$project_root/work/generated-corpus.tmp.XXXXXX")
recipe=$(mktemp "$project_root/work/generated-corpus-recipe.tmp.XXXXXX")
cleanup() {
  [[ ! -d "$staging" ]] || rm -rf -- "$staging"
  [[ ! -f "$recipe" ]] || rm -f -- "$recipe"
}
trap cleanup EXIT
version=$(ffmpeg -version 2>/dev/null)
version=${version%%$'\n'*}
printf '%s\n\nSynthetic sources: 997Hz sine or seeded pink noise. No input media files.\n' "$version" > "$recipe"
printf 'Run parity/helpers/generate-media-fixtures.sh --replace to regenerate the managed corpus.\nAll files are decoded by FFmpeg before replacing an existing corpus.\n\n' >> "$recipe"
total_bytes=0
file_count=0

sine() { printf 'sine=frequency=997:sample_rate=%s:duration=%s' "$1" "$2"; }
noise() { printf 'anoisesrc=color=pink:amplitude=0.12:seed=314159:sample_rate=%s:duration=%s' "$1" "$2"; }
generate() {
  local name=$1 source=$2 channel_count=$3
  shift 3
  local -a command=(ffmpeg -hide_banner -loglevel error -nostdin -n -f lavfi -i "$source"
    -ac "$channel_count" -map_metadata -1
    -metadata 'title=Generated test — Žluťoučký' -metadata 'artist=TagLib Java validation'
    -metadata 'album=Independent synthetic corpus'
    -metadata 'comment=997Hz sine or seeded pink noise; generated by FFmpeg'
    -metadata date=2026 -metadata track=7 -metadata genre=Jazz "$@")
  printf '%q ' "${command[@]}" "$corpus/$name" >> "$recipe"
  printf '\n' >> "$recipe"
  "${command[@]}" "$staging/$name"
  local byte_count
  byte_count=$(wc -c < "$staging/$name")
  total_bytes=$((total_bytes + byte_count))
  if ((total_bytes > 30 * 1024 * 1024)); then
    printf 'Corpus exceeded the 30 MiB budget; existing corpus retained.\n' >&2
    exit 1
  fi
  ffmpeg -hide_banner -loglevel error -nostdin -i "$staging/$name" -map 0:a:0 -f null -
  file_count=$((file_count + 1))
  printf '%s: %s bytes; full decode passed\n' "$name" "$byte_count"
}

generate sine-vbr-30s.mp3 "$(sine 44100 30)" 2 -c:a libmp3lame -q:a 3
generate pink-cbr-7s.mp3 "$(noise 48000 7)" 1 -c:a libmp3lame -b:a 96k
generate sine-layer2-7s.mp2 "$(sine 48000 7)" 2 -c:a mp2 -b:a 128k
generate pink-16bit-30s.flac "$(noise 48000 30)" 2 -c:a flac -sample_fmt s16 -compression_level 5
generate sine-vorbis-7s.ogg "$(sine 44100 7)" 2 -c:a libvorbis -q:a 4
generate pink-opus-30s.opus "$(noise 48000 30)" 2 -c:a libopus -b:a 96k
if [[ "$encoder_list" == *' libspeex '* ]]; then
  generate sine-speex-7s.spx "$(sine 16000 7)" 1 -c:a libspeex -q:a 5
else
  printf 'Optional libspeex encoder unavailable; Speex fixture skipped.\n' | tee -a "$recipe"
fi
generate sine-oggflac-7s.oga "$(sine 44100 7)" 2 -c:a flac -sample_fmt s16 -f ogg
generate pink-aac-30s.m4a "$(noise 44100 30)" 2 -c:a aac -b:a 192k -movflags +faststart
generate sine-alac-24bit-7s.m4a "$(sine 96000 7)" 2 -c:a alac -sample_fmt s32p
generate pink-pcm24-30s.wav "$(noise 48000 30)" 2 -c:a pcm_s24le
generate sine-rf64-7s.wav "$(sine 44100 7)" 1 -c:a pcm_s16le -rf64 always
generate sine-pcm16-7s.aiff "$(sine 44100 7)" 1 -c:a pcm_s16be -write_id3v2 1
generate sine-wavpack-7s.wv "$(sine 96000 7)" 2 -c:a wavpack -sample_fmt s16p
generate sine-trueaudio-7s.tta "$(sine 44100 7)" 2 -c:a tta -sample_fmt s16
generate pink-wmav2-7s.wma "$(noise 44100 7)" 2 -c:a wmav2 -b:a 128k
generate sine-matroska-flac-7s.mka "$(sine 48000 7)" 2 -c:a flac -sample_fmt s16

# Generation and decoding succeeded. Delete only the previously validated managed files.
for entry in "${existing[@]}"; do rm -- "$entry"; done
if [[ -d "$corpus" ]]; then rmdir -- "$corpus"; fi
mv -- "$staging" "$corpus"
printf '%s\n' "$signature" > "$owner"
printf '\nFiles: %s\nTotal bytes: %s\n' "$file_count" "$total_bytes" >> "$recipe"
mv -- "$recipe" "$project_root/work/generated-corpus-recipe.txt"
printf 'Generated %s files (%s bytes) in %s\n' "$file_count" "$total_bytes" "$corpus"
printf 'Recipe: %s/work/generated-corpus-recipe.txt\n' "$project_root"
